def place_creature_eyes(body):
    """Eye centres on the smoothed face (paint_true_face and the previews use them)."""
    me = body.data
    me.calc_loop_triangles()
    co = [tuple(v.co) for v in me.vertices]
    tris = [tuple(t.vertices) for t in me.loop_triangles]
    bvh = BVHTree.FromPolygons(co, tris)
    for k in (-1, 1):
        hit = bvh.ray_cast(V((ss.EYE_X * k, -1.0, ss.EYE_Z)), V((0, 1, 0)))[0]
        ey = (hit.y if hit is not None else -0.2) + ss.EYE_R * 0.55
        ss.EYE_CENTRES[k] = V((ss.EYE_X * k, ey, ss.EYE_Z))
    log('creature eyes', {k: tuple(round(x, 3) for x in v) for k, v in ss.EYE_CENTRES.items()})
    return bvh


def keep_hands_above_floor():
    """v1's floor poses (folded at the start of `reveal`, kneel and collapse in `death`) swing the arms by angle.
    With the concept's longer arms that pushes hands 20 cm into the floor, so after every solve an arm whose elbow,
    wrist or fingertips end up below the floor is re-aimed (two-bone IK) with the hand laid flat on it."""
    reach = (ss.FJ['L']['middle'][-1] - ss.WRIST['L']).length
    solve = ss.Rig.solve
    lifted = [0]

    def solve_on_floor(self, s):
        basis = solve(self, s)
        posed = self.fk(basis)
        for side, k in SIDES.items():
            hand = posed['hand_' + side]
            wrist, elbow = hand.translation.copy(), posed['forearm_' + side].translation.copy()
            d = (hand.to_3x3() @ V((0, 1, 0))).normalized()
            tip = wrist + d * reach
            low = min(wrist.z - 0.05, tip.z - 0.02, elbow.z - 0.08)
            if low >= 0:
                continue
            flat = V((d.x, d.y, max(d.z, -0.12))).normalized()
            target = V((wrist.x, wrist.y, max(wrist.z - low, 0.05)))
            if target.z + flat.z * reach < 0.02:
                target.z = 0.02 - flat.z * reach
            self.two_bone(basis, posed, 'upperarm_' + side, 'forearm_' + side, 'hand_' + side, target,
                          V((0.9 * k, 0.3, 0.6)))
            rest_dir = (ss.BONES['hand_' + side][1] - ss.BONES['hand_' + side][0]).normalized()
            q = rest_dir.rotation_difference(flat)
            self.set_orient(basis, posed, 'hand_' + side, q.to_matrix() @ self.rest3['hand_' + side])
            posed = self.fk(basis)
            lifted[0] += 1
        return basis
    ss.Rig.solve = solve_on_floor
    return lifted


ARM = ('clavicle', 'upperarm', 'forearm', 'hand')


def part_labels(P, hi_co, hi_tri, part, bvh=None):
    """Body part of each point: the fit's part (A-pose segmentation) of the nearest scan vertex."""
    bvh = bvh or BVHTree.FromPolygons(hi_co.tolist(), hi_tri.tolist())
    lab = []
    for p in P.tolist():
        loc, _n, f, _d = bvh.find_nearest(p)
        vs = hi_tri[f]
        lab.append(part[vs[np.argmin(np.linalg.norm(hi_co[vs] - np.array(loc), axis=1))]])
    return np.array(lab), bvh


def cut_arm_webs(body, hi_co, hi_tri, part):
    """The scan joins the right sleeve to the cardigan's front panel in one sheet (a web under the arm), which tears
    into a spike when the arm swings up. Faces between arm vertices and body vertices below the armpit are removed,
    so sleeve and panel part like the torn cardigan they are."""
    bm = bmesh.new()
    bm.from_mesh(body.data)
    bm.verts.ensure_lookup_table()
    P = np.array([tuple(v.co) for v in bm.verts])
    lab, bvh = part_labels(P, hi_co, hi_tri, part)
    cut = []
    for s in SIDES:
        arm_v = np.isin(lab, ['upperarm_' + s, 'forearm_' + s, 'hand_' + s])
        armpit = ss.SHOULDER[s].z - 0.12
        for f in bm.faces:
            ids = [v.index for v in f.verts]
            a = arm_v[ids]
            if a.any() and not a.all() and f.calc_center_median().z < armpit:
                cut.append(f)
    bmesh.ops.delete(bm, geom=list(set(cut)), context='FACES')
    loose = [v for v in bm.verts if not v.link_faces]
    bmesh.ops.delete(bm, geom=loose, context='VERTS')
    bm.to_mesh(body.data)
    bm.free()
    log('cut %d faces between the arms and the body below the armpits' % len(set(cut)))
    return bvh


def skin_body(body, hi_co, hi_tri, part):
    """v1's distance weights (radii from build_skin_stealer.SEG_R), limited by body part. The scan's arms are thicker
    than v1's and its fingers longer, so by distance alone the inside of a forearm "belongs" to the pelvis and a
    fingertip to the hip. The part each vertex had in the fit (measured in the A-pose, where the arms stand clear of
    the body) decides which bones it may use: arm vertices only that arm's bones, the rest no forearm, hand or
    finger bone."""
    for n in ss.BONES:
        body.vertex_groups.new(name=n)
    bm = bmesh.new()
    bm.from_mesh(body.data)
    bm.verts.ensure_lookup_table()
    bm.verts.index_update()
    P = ss.bm_coords(bm)
    edges = np.array([(e.verts[0].index, e.verts[1].index) for e in bm.edges])
    lab, _bvh = part_labels(P, hi_co, hi_tri, part)

    fingers = set(ss.FINGER_BONES['L'] + ss.FINGER_BONES['R'])

    def may_use(names):
        M = np.ones((len(P), len(names)), bool)
        for j, n in enumerate(names):
            if n in fingers:
                M[:, j] = False      # the scan's fingers do not follow v1's finger bones: hands stay rigid claws
                continue
            base, _, side = n.rpartition('_')
            for s_ in SIDES:
                in_arm = np.isin(lab, ['upperarm_' + s_, 'forearm_' + s_, 'hand_' + s_])
                near_shoulder = np.linalg.norm(P - np.array(tuple(ss.SHOULDER[s_])), axis=1) < 0.2
                if base in ARM and side == s_:
                    if base not in ('clavicle', 'upperarm'):
                        M[~in_arm, j] = False
                    else:   # torso vertices may use the clavicle and upper arm only round the shoulder
                        M[~in_arm & ~near_shoulder, j] = False
                elif n == 'spine_03':
                    M[in_arm & ~near_shoulder, j] = False
                else:
                    M[in_arm, j] = False
        return M

    segs = {n: (ss.BONES[n][0], ss.BONES[n][1]) for n in ss.BONES if n not in ss.NO_BODY_WEIGHT}
    names, W = seg_weights(P, segs, edges, smooth=5, may_use=may_use)
    deform = bm.verts.layers.deform.verify()
    gi = {g.name: g.index for g in body.vertex_groups}
    for k, v in enumerate(bm.verts):
        dv = v[deform]
        dv.clear()
        for j in np.nonzero(W[k] > 1e-4)[0]:
            dv[gi[names[j]]] = float(W[k, j])
    bm.to_mesh(body.data)
    bm.free()
    log('skin weights: %d vertices on arm bones only' % int(np.isin(lab, [b + '_' + s_ for b in ARM for s_ in SIDES]).sum()))


def main():
    common.reset_scene()
    co, tri = load_scan()
    fitted, co, J, part = fit_to_skeleton(co, tri)
    if STAGE == 'fit':
        hi = make_mesh('scan_hi', fitted, tri)
        projection_overlay(load_views(co), co)
        check_fit(hi)
        return
    hi_co = smooth_face(fitted, tri)
    body = make_mesh('skin_stealer_body', hi_co, tri)
    decimate(body, int(ARGS.get('tris', 11500)))
    env = place_creature_eyes(body)
    mask = ss.build_mask(env)
    ss.unwrap([body, mask])
    tex = paint_atlas(body, mask, hi_co, tri, co, part)
    m_skin, m_human, m_slime = ss.build_materials(tex)
    m_skin.use_backface_culling = False   # the cardigan's torn edges are thin, single surfaces after decimation
    common.assign(body, m_skin)
    common.assign(mask, m_human)
    arm = ss.build_armature()
    cut_arm_webs(body, hi_co, tri, part)
    skin_body(body, hi_co, tri, part)
    ss.add_body_shape_keys(body, None)
    mask.vertex_groups.new(name='mask').add(list(range(len(mask.data.vertices))), 1.0, 'REPLACE')
    ss.add_mask_shape_keys(mask, env)
    for o in (body, mask):
        o.parent = arm
        o.modifiers.new('Armature', 'ARMATURE').object = arm
    bottle = ss.build_bottle(arm, m_slime, ss.slime_uv_spot(tex['slime']))
    ss.add_sockets(arm)
    lifted = keep_hands_above_floor()
    rig = ss.Rig(arm)
    acts = ss.build_actions(rig, bottle)
    log('floor guard lifted an arm in %d solved frames' % lifted[0])
    log('TRIS total', common.triangle_count(), {o.name: common.triangle_count([o]) for o in
                                                 bpy.context.scene.objects if o.type == 'MESH'})
    path = common.export_glb(ss.OUT_NAME)
    log('EXPORTED', path, path.stat().st_size, 'bytes')
    ss.check_glb(path)
    ss.floor_check(arm, body, acts)
    if STAGE != 'noprev':
        ss.previews(arm, body, mask, bottle, acts)
    log('done')


main()
