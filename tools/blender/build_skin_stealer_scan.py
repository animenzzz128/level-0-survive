def project_colours(views, P_scan, N_scan, bvh_scan):
    M = len(P_scan)
    acc = np.zeros((M, 3))
    wsum = np.zeros(M)
    for name, v in views.items():
        _ax, _sign, d = VIEW_AXES[name]
        cos = N_scan @ d
        cand = np.nonzero(cos > 0.03)[0]
        px, py = view_pixels(v, name, P_scan[cand])
        h, w = v['fg'].shape
        inb = (px >= 0) & (px < w - 1) & (py >= 0) & (py < h - 1)
        cand, px, py = cand[inb], px[inb], py[inb]
        # where the scan reaches past the drawn outline, take the colour of the nearest drawn pixel
        iy, ix = py.astype(int), px.astype(int)
        dist = v['dist'][iy, ix]
        near = dist < 25
        cand, px, py, iy, ix, dist = cand[near], px[near], py[near], iy[near], ix[near], dist[near]
        out = dist > 0
        px[out] = v['near'][iy[out], ix[out], 1].astype(float)
        py[out] = v['near'][iy[out], ix[out], 0].astype(float)
        snap_w = 1.0 - dist / 25.0
        dv = Vector(tuple(d))
        vis = np.ones(len(cand), bool)
        origins = (P_scan[cand] + d * 0.004).tolist()
        for i, o in enumerate(origins):
            if bvh_scan.ray_cast(o, dv, 3.0)[0] is not None:
                vis[i] = False
        cand, px, py, snap_w = cand[vis], px[vis], py[vis], snap_w[vis]
        wv = cos[cand] ** 2 * v['weight'] * snap_w
        acc[cand] += wv[:, None] * sample(v['img'], px, py)
        wsum[cand] += wv
        log('projected %-5s onto %d texels (%d hidden)' % (name, len(cand), int((~vis).sum())))
    col = acc / np.maximum(wsum, 1e-9)[:, None]
    return col, wsum


def fill_unseen(P, col, wsum, thr=0.06, cell=0.01):
    """Texels no view sees well (the right flank, armpits, soles, the top of the head) take the colour of nearby
    seen surface: normalised convolution on a 3D grid, at the smallest scale that reaches a seen texel."""
    good = wsum >= thr * 0.5
    origin = P.min(0) - 2 * cell
    dims = tuple(np.ceil((P.max(0) - origin) / cell).astype(int) + 3)
    idx = ((P - origin) / cell).astype(int)
    acc = np.zeros(dims + (3,))
    cnt = np.zeros(dims)
    gi = tuple(idx[good].T)
    for a in range(3):
        np.add.at(acc[..., a], gi, col[good, a] * wsum[good])
    np.add.at(cnt, gi, wsum[good])
    bad = np.nonzero(wsum < thr)[0]
    q = (P[bad] - origin) / cell - 0.5          # cell centres sit at +0.5
    q0 = np.floor(q).astype(int)
    f = q - q0
    corners = []
    for dx in (0, 1):
        for dy in (0, 1):
            for dz in (0, 1):
                wgt = (f[:, 0] if dx else 1 - f[:, 0]) * (f[:, 1] if dy else 1 - f[:, 1]) * (f[:, 2] if dz else 1 - f[:, 2])
                ci = np.clip(q0 + np.array([dx, dy, dz]), 0, np.array(dims) - 1)
                corners.append((tuple(ci.T), wgt))

    def lookup(grid):
        return sum(grid[ci] * (wgt[:, None] if grid.ndim == 4 else wgt) for ci, wgt in corners)

    fill = np.zeros((len(bad), 3))
    done = np.zeros(len(bad), bool)
    level = 0
    while not done.all() and level < 7:
        c = lookup(cnt)
        take = (~done) & (c > 1e-3)
        fill[take] = lookup(acc)[take] / c[take, None]
        done |= take
        for _ in range(2 ** level):
            for ax in range(3):
                acc = (acc + np.roll(acc, 1, axis=ax) + np.roll(acc, -1, axis=ax)) / 3
                cnt = (cnt + np.roll(cnt, 1, axis=ax) + np.roll(cnt, -1, axis=ax)) / 3
        level += 1
    fill[~done] = np.median(col[good], axis=0)
    a = np.clip(wsum[bad] / thr, 0, 1)[:, None]
    out = col.copy()
    out[bad] = col[bad] * a + fill * (1 - a)
    log('filled %d texels no view saw well' % len(bad))
    return out


def colour_kinds(col):
    """Rough classes from the projected colour: pale-yellow creature skin, grey cardigan, pink stolen skin."""
    r, g, b = col[:, 0], col[:, 1], col[:, 2]
    sat = col.max(1) - col.min(1)
    skin = ss.smoothstep(0.10, 0.18, r - b) * ss.smoothstep(-0.02, 0.04, g - b * 1.05) * (1 - ss.smoothstep(0.06, 0.12, r - g))
    pink = ss.smoothstep(0.06, 0.12, r - g)
    grey = 1 - ss.smoothstep(0.04, 0.09, sat)
    return skin, grey, pink


