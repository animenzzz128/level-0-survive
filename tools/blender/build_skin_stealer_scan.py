def paint_true_face(P, c, h, skin_col):
    """Under the mask: the creature's own skin, sunken white eyes and the dark round mouth hole (as in v1)."""
    inside = ss.smoothstep(-0.012, 0.0, face_oval(P)) * (P[:, 1] < ss.HEAD_C.y) * (P[:, 2] > 1.86)
    c = ss.mix(c, skin_col, inside)
    face_front = (P[:, 1] < ss.HEAD_C.y - 0.04) & (P[:, 2] > 1.9)
    for _k, ec in ss.EYE_CENTRES.items():
        # eyes as disks seen from the front: the smoothed face is not quite square to the camera, so a 3D sphere
        # (v1) can miss the surface on one side
        rr = np.hypot(P[:, 0] - ec.x, P[:, 2] - ec.z)
        eye = face_front & (rr < ss.EYE_R)
        if eye.any():
            ce = np.tile(np.array([0.90, 0.89, 0.83]), (int(eye.sum()), 1))
            c[eye] = ss.mix(ce, (0.74, 0.75, 0.73), 0.5 * np.exp(-((rr[eye] - 0.0045) / 0.0012) ** 2))
            h[eye] = -0.0015 * (1 - (rr[eye] / ss.EYE_R) ** 2)
        sock = (~eye) & face_front & (rr < 0.03)
        c[sock] = ss.mix(c[sock], (0.62, 0.55, 0.36), 0.5 * (1 - ss.smoothstep(0.012, 0.03, rr[sock])))
    rr = np.hypot(P[:, 0] - ss.MOUTH_X, P[:, 2] - ss.MOUTH_Z)
    mz = (rr < 0.03) & face_front & (P[:, 2] > 1.94)
    dark = 1 - ss.smoothstep(0.0175, 0.0205, rr[mz])     # a sharp-edged hole (v1's soft edge blurs at this density)
    c[mz] = ss.mix(ss.mix(c[mz], (0.30, 0.17, 0.13), 0.6 * (1 - ss.smoothstep(0.019, 0.028, rr[mz]))),
                   (0.035, 0.022, 0.016), dark)
    h[mz] *= 1 - dark
    return c, h


def sucker_height(P, N, skin):
    """Small and large sucker cups on the creature's bare skin (v1's pattern, a little weaker: the concept colour
    already carries painted bumps)."""
    w_large = np.clip(0.62 + 0.6 * ss.fbm(P, 2.5, 2, 23) + 0.35 * np.clip(N[:, 1], 0, 1), 0, 1)
    dens = ss.smoothstep(-0.35, 0.15, ss.fbm(P, 5.0, 2, 24) + 0.25) * skin
    rs, cs = ss.sucker_profile(ss.worley(P, 0.0085, 31, keep=0.75))
    rl, cl = ss.sucker_profile(ss.worley(P, 0.0185, 41, keep=0.72))
    ring = ((1 - w_large) * rs + w_large * rl) * dens
    cup = ((1 - w_large) * cs + w_large * cl) * dens
    amp = (1 - w_large) * 0.0004 + w_large * 0.0009
    return amp * (ring - 0.8 * cup), ring, cup


def height_to_normal(H, valid, pos, tsz):
    """Tangent-space normal from a height map in metres (v1's finite differences)."""
    T = tsz.astype(np.float64)
    gx, gy = np.zeros_like(H), np.zeros_like(H)
    for axis, g in ((1, gx), (0, gy)):
        fwd, bwd = np.roll(H, -1, axis=axis), np.roll(H, 1, axis=axis)
        vf = np.roll(valid, -1, axis=axis) & (np.linalg.norm(np.roll(pos, -1, axis=axis) - pos, axis=2) < 4 * T + 1e-4)
        vb = np.roll(valid, 1, axis=axis) & (np.linalg.norm(np.roll(pos, 1, axis=axis) - pos, axis=2) < 4 * T + 1e-4)
        num = np.where(vf, fwd, H) - np.where(vb, bwd, H)
        den = (vf.astype(float) + vb.astype(float)) * np.maximum(T, 1e-6)
        g[:] = np.where(valid & (den > 0), num / np.maximum(den, 1e-9), 0.0)
    return gx, gy


def paint_atlas(body, mask, hi_co, hi_tri, scan_co, part, size=2048):
    UVb, P3b, N3b, Lb = gather(body, 0)
    UVm, P3m, N3m, Lm = gather(mask, 1)
    UV, P3, N3, LAB = (np.concatenate(x) for x in ((UVb, UVm), (P3b, P3m), (N3b, N3m), (Lb, Lm)))
    pos, nrm, lab, tid, tsz = rasterize(UV, P3, N3, LAB, size)
    Tf, Bf = tangent_frames(UV, P3)
    valid = lab >= 0
    log('atlas: %d texels of %d' % (int(valid.sum()), size * size))
    yy, xx = np.nonzero(valid)
    P = pos[yy, xx].astype(np.float64)
    Nl = nrm[yy, xx].astype(np.float64)
    Nl /= np.maximum(np.linalg.norm(Nl, axis=1, keepdims=True), 1e-9)
    L = lab[yy, xx]
    body_t = np.nonzero(L == 0)[0]
    mask_t = np.nonzero(L == 1)[0]

    # nearest point on the full-resolution (fitted, face-smoothed) scan -> same spot on the unfitted scan
    bvh_hi = BVHTree.FromPolygons(hi_co.tolist(), hi_tri.tolist())
    fidx = np.zeros(len(body_t), np.int64)
    loc = np.zeros((len(body_t), 3))
    for i, p in enumerate(P[body_t].tolist()):
        l, _n, f, _d = bvh_hi.find_nearest(p)
        if f is None:
            f, l = 0, p
        fidx[i] = f
        loc[i] = l
    log('nearest points found')
    tri_f = hi_tri[fidx]
    bc = barycentric(loc, hi_co[tri_f[:, 0]], hi_co[tri_f[:, 1]], hi_co[tri_f[:, 2]])
    hn = vertex_normals(hi_co, hi_tri)
    sn = vertex_normals(scan_co, hi_tri)
    N_hi = (bc[:, :, None] * hn[tri_f]).sum(1)
    P_scan = (bc[:, :, None] * scan_co[tri_f]).sum(1)
    N_scan = (bc[:, :, None] * sn[tri_f]).sum(1)
    N_hi /= np.maximum(np.linalg.norm(N_hi, axis=1, keepdims=True), 1e-9)
    N_scan /= np.maximum(np.linalg.norm(N_scan, axis=1, keepdims=True), 1e-9)

    views = load_views(scan_co)
    bvh_scan = BVHTree.FromPolygons(scan_co.tolist(), hi_tri.tolist())
    col_b, wsum = project_colours(views, P_scan, N_scan, bvh_scan)
    col_b = fill_unseen(P[body_t], col_b, wsum)
    skin, grey, pink = colour_kinds(col_b)
    skin_col = np.median(col_b[skin > 0.8], axis=0) if (skin > 0.8).sum() > 100 else np.array(ss.C_SKIN)
    log('skin colour from the concept', skin_col.round(3), 'skin texels %.0f%%' % (100 * (skin > 0.5).mean()))
    # Above the neck the concept shows the stolen human face; the game's own mask mesh plays that part, so the
    # head gets the creature's mottled skin all round.
    Pb = P[body_t]
    head = ss.smoothstep(1.86, 1.93, Pb[:, 2])
    own = np.tile(skin_col, (len(Pb), 1)) * (1 + 0.07 * ss.fbm(Pb, 7.0, 3, 21))[:, None]
    own = ss.mix(own, skin_col * np.array([1.05, 1.03, 0.95]), 0.3 * ss.smoothstep(0.1, 0.6, ss.fbm(Pb, 3.0, 2, 22)))
    col_b = ss.mix(col_b, own, head)
    skin = np.maximum(skin, head)
    # Loose cloth: the cardigan's panels are thin sheets in the scan. Where the drawing and the scan disagree they
    # picked up skin colour and read as wings, so anything under 2.5 cm thick (hands excepted) is knit grey.
    thick = np.full(len(body_t), 1.0)
    origins = (loc - N_hi * 0.002).tolist()
    for i, (o, nv) in enumerate(zip(origins, (-N_hi).tolist())):
        hit = bvh_hi.ray_cast(o, nv, 0.06)
        if hit[0] is not None:
            thick[i] = hit[3] + 0.002
    hand = np.char.startswith(part[tri_f[:, 0]].astype(str), 'hand')
    cloth = (thick < 0.025) & ~hand & (Pb[:, 2] < 1.88)
    knit_col = np.median(col_b[(grey > 0.8) & (pink < 0.2)], axis=0) if ((grey > 0.8) & (pink < 0.2)).sum() > 100         else np.array(ss.C_KNIT)
    knit = np.tile(knit_col, (len(Pb), 1)) * (0.9 + 0.12 * ss.fbm(Pb, 9.0, 3, 81))[:, None]
    knit = ss.mix(knit, knit_col * 0.6, 0.35 * ss.smoothstep(0.2, 0.7, ss.fbm(Pb, 4.0, 2, 82)))
    recolour = cloth & (grey < 0.5) & (pink < 0.5)
    col_b[recolour] = knit[recolour]
    skin = skin * ~cloth
    log('cloth: %d texels thinner than 2.5 cm, %d recoloured to knit grey %s' % (
        int(cloth.sum()), int(recolour.sum()), np.round(knit_col, 3)))
    h_b, ring, cup = sucker_height(P[body_t], N_hi, skin)
    col_b = col_b * (1 + 0.08 * ring)[:, None]
    col_b = ss.mix(col_b, skin_col * 0.78, 0.5 * cup)
    col_b, h_b = paint_true_face(P[body_t], col_b, h_b, skin_col)
    col_m, h_m = paint_mask_texels(P[mask_t])

    base = np.zeros((size, size, 3), np.float32)
    base[yy[body_t], xx[body_t]] = np.clip(col_b, 0, 1)
    base[yy[mask_t], xx[mask_t]] = np.clip(col_m, 0, 1)
    base = ss.dilate(base, valid, 8)

    # normal map: the scan's detail in the game mesh's tangent space, plus the sucker relief
    t_ids = tid[yy, xx]
    T = Tf[t_ids]
    Bv = Bf[t_ids]
    T = T - Nl * (T * Nl).sum(1, keepdims=True)
    T /= np.maximum(np.linalg.norm(T, axis=1, keepdims=True), 1e-12)
    handed = np.sign((np.cross(Nl, T) * Bv).sum(1))
    handed[handed == 0] = 1
    Bo = np.cross(Nl, T) * handed[:, None]
    n_ts = np.zeros((len(P), 3))
    n_ts[:, 2] = 1.0
    nb = N_hi
    n_ts[body_t] = np.stack([(nb * T[body_t]).sum(1), (nb * Bo[body_t]).sum(1), (nb * Nl[body_t]).sum(1)], 1)
    n_ts[:, 2] = np.maximum(n_ts[:, 2], 0.2)
    Hm = np.zeros((size, size))
    Hm[yy[body_t], xx[body_t]] = h_b
    Hm[yy[mask_t], xx[mask_t]] = h_m
    gx, gy = height_to_normal(Hm, valid, pos, tsz)
    n_ts[:, 0] -= gx[yy, xx]
    n_ts[:, 1] -= gy[yy, xx]
    n_ts /= np.linalg.norm(n_ts, axis=1, keepdims=True)
    nmap = np.zeros((size, size, 3))
    nmap[..., 2] = 1.0
    nmap[yy, xx] = n_ts
    half = size // 2
    v4 = valid.reshape(half, 2, half, 2)
    n4 = (nmap * valid[..., None]).reshape(half, 2, half, 2, 3).sum(axis=(1, 3))
    vsmall = v4.sum(axis=(1, 3)) > 0
    n4 /= np.maximum(np.linalg.norm(n4, axis=2, keepdims=True), 1e-9)
    n4[~vsmall] = (0, 0, 1)
    n4 = ss.dilate(n4, vsmall, 6)
    n4 /= np.maximum(np.linalg.norm(n4, axis=2, keepdims=True), 1e-9)
    slime = np.zeros((64, 64, 4), np.float32)
    slime[..., :3] = (0.93, 0.94, 0.87)
    slime[..., 3] = np.linspace(0.2, 0.7, 64)[None, :]
    return {
        'base': ss.encode_image('ss_skin_basecolor', base, 'JPEG', 88),
        'normal': ss.encode_image('ss_skin_normal', (n4 * 0.5 + 0.5).astype(np.float32), 'JPEG', 92, non_color=True),
        'slime': ss.encode_image('ss_slime', slime, 'PNG', 100),
    }


