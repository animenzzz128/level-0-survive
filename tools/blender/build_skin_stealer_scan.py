"""Build public/assets/models/ent_skin_stealer.glb from a Hunyuan3D scan of the concept turnaround (model v2).

    blender --background --factory-startup --python tools/blender/build_skin_stealer_scan.py
    (add `-- stage=fit` to stop after fitting the scan to the skeleton and render a check,
     or `-- stage=noprev` to skip the preview renders)

The shape comes from tools/blender/sources/skin_stealer_hunyuan2mv.glb, generated by Hunyuan3D-2mv from three crops
of docs/design/art/concepts/skin-stealer/B_turnaround.webp (settings and licence: tools/hunyuan/README.md).
This script:
  1. scales the scan to 2.27 m and measures its joints;
  2. bends it onto the v1 skeleton of build_skin_stealer.py (linear-blend skinning, one transform per bone), so
     the v1 rig, clips, sockets, stolen-face mask and disguise bottle carry over unchanged;
  3. smooths the scanned face under the mask into the creature's own face (sunken eyes and a mouth hole are
     painted and shaped later, as in v1);
  4. decimates to the game budget and paints one atlas: colour projected from the three concept views with an
     occlusion test, the scan's surface detail as a tangent-space normal map, procedural suckers on the bare skin;
  5. skins, adds the shape keys, sockets and clips from build_skin_stealer.py, exports, and renders previews.
"""
