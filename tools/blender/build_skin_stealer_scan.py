def vertex_normals(co, tri):
    fn = np.cross(co[tri[:, 1]] - co[tri[:, 0]], co[tri[:, 2]] - co[tri[:, 0]])
    vn = np.zeros_like(co)
    for i in range(3):
        for a in range(3):
            vn[:, a] += np.bincount(tri[:, i], weights=fn[:, a], minlength=len(co))
    return vn / np.maximum(np.linalg.norm(vn, axis=1, keepdims=True), 1e-12)


def face_oval(P):
    """Positive inside the mask's face oval (without its eye and mouth holes), in metres."""
    u, v = ss.mask_uv_from_world(P)
    return (1.0 - np.sqrt((u / 0.075) ** 2 + ((v + 0.022) / np.where(v + 0.022 > 0, 0.10, 0.12)) ** 2)) * 0.075


def smooth_face(co, tri, iters=120):
    """The scan carries the concept's human face. Under the mask the creature has its own flat face (sunken eyes and
    a mouth hole are added by the texture and the shape keys), so the scanned features are smoothed away there and
    the surface is pulled 4 mm in to make room for the mask."""
    w = ss.smoothstep(-0.045, 0.0, face_oval(co)) * (co[:, 1] < ss.HEAD_C.y + 0.03) * (co[:, 2] > 1.82)
    region = w > 0
    edges = mesh_edges(tri)
    edges = edges[region[edges[:, 0]] | region[edges[:, 1]]]
    n = len(co)
    cnt = np.bincount(edges[:, 0], minlength=n) + np.bincount(edges[:, 1], minlength=n)
    P = co.copy()
    for _ in range(iters):
        avg = np.zeros_like(P)
        for a in range(3):
            avg[:, a] = (np.bincount(edges[:, 0], weights=P[edges[:, 1], a], minlength=n)
                         + np.bincount(edges[:, 1], weights=P[edges[:, 0], a], minlength=n))
        avg /= np.maximum(cnt, 1)[:, None]
        P[region] += (0.6 * w[region])[:, None] * (avg[region] - P[region])
    P -= vertex_normals(P, tri) * (0.004 * w)[:, None]
    log('face: smoothed %d vertices under the mask' % int(region.sum()))
    return P


