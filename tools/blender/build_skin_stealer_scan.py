# 2. Joints of the scan, and the bend onto the v1 skeleton
# ---------------------------------------------------------------------------------------------------------------
def slice_c(pts, z, half=0.012, mid_x=False):
    s = pts[np.abs(pts[:, 2] - z) < half]
    if len(s) < 5:
        raise RuntimeError('empty slice at z=%.3f' % z)
    x = 0.5 * (s[:, 0].min() + s[:, 0].max()) if mid_x else s[:, 0].mean()
    return V((x, 0.5 * (s[:, 1].min() + s[:, 1].max()), z))


def line_at(pts, z_lo, z_hi, z):
    """Fit x(z), y(z) to slice centroids in [z_lo, z_hi] and evaluate at z."""
    zs = np.arange(z_lo, z_hi + 1e-6, 0.02)
    cs = np.array([tuple(slice_c(pts, zz)) for zz in zs])
    px, py = np.polyfit(cs[:, 2], cs[:, 0], 1), np.polyfit(cs[:, 2], cs[:, 1], 1)
    return V((np.polyval(px, z), np.polyval(py, z), z))


def scan_joints(co):
    B = ss.BONES
    J = {}
    torso = co[np.abs(co[:, 0]) < 0.22]
    spine = [slice_c(torso, p.z, mid_x=True) for p in ss.SPINE[:4]]
    for p in spine:
        p.x = 0.0
    neck = co[np.abs(co[:, 0]) < 0.09]
    spine.append(slice_c(neck, ss.SPINE[4].z))
    spine[-1].x = 0.0
    head = co[(co[:, 2] > 1.9)]
    spine.append(slice_c(head, ss.SPINE[5].z, mid_x=True))
    spine.append(slice_c(head, ss.SPINE[6].z - 0.03, mid_x=True))
    spine[-1].z = ss.SPINE[6].z
    J['spine'] = spine
    for s, k in SIDES.items():
        leg = co[(k * co[:, 0] > 0.012) & (np.abs(co[:, 0]) < 0.25) & (co[:, 2] < 1.0)]
        knee = slice_c(leg, ss.KNEE[s].z)
        p80 = slice_c(leg, 0.80)
        hip = knee + (p80 - knee) * ((ss.HIP[s].z - knee.z) / (p80.z - knee.z))
        ank = slice_c(leg, 0.12)
        ank.z = ss.ANKLE[s].z
        foot = leg[leg[:, 2] < 0.05]
        toe = V(tuple(foot[np.argmin(foot[:, 1])]))
        toe.z = ss.TOE[s].z
        ball = ank + (toe - ank) * 0.68
        ball.z = ss.BALL[s].z
        J['hip', s], J['knee', s], J['ankle', s], J['ball', s], J['toe', s] = hip, knee, ank, ball, toe
        arm = co[(k * co[:, 0] > 0.30) & (co[:, 2] < 1.72) & (co[:, 2] > 0.25)]
        z_tip = arm[:, 2].min()
        S0, E0, W0 = B['upperarm_' + s][0], B['forearm_' + s][0], B['hand_' + s][0]
        tip0 = ss.FJ[s]['middle'][-1]
        hand_end0 = B['hand_' + s][1]
        sh = line_at(arm, 1.40, 1.62, S0.z)
        span, span0 = sh.z - z_tip, S0.z - tip0.z
        el = slice_c(arm, sh.z - span * (S0.z - E0.z) / span0)
        wr = slice_c(arm, sh.z - span * (S0.z - W0.z) / span0)
        tip = arm[arm[:, 2] < z_tip + 0.02].mean(axis=0)
        J['shoulder', s], J['elbow', s], J['wrist', s], J['tip', s] = sh, el, wr, V(tuple(tip))
        J['clav_in', s] = B['clavicle_' + s][0] + (spine[4] - ss.SPINE[4])
    return J


FIT_BONES = ['pelvis', 'spine_01', 'spine_02', 'spine_03', 'neck', 'head'] + [
    b + '_' + s for s in SIDES for b in ('clavicle', 'upperarm', 'forearm', 'hand', 'thigh', 'shin', 'foot', 'toe')]


def scan_segments(J):
    sp = J['spine']
    seg = {'pelvis': (sp[0], sp[1]), 'spine_01': (sp[1], sp[2]), 'spine_02': (sp[2], sp[3]),
           'spine_03': (sp[3], sp[4]), 'neck': (sp[4], sp[5]), 'head': (sp[5], sp[6])}
    for s in SIDES:
        seg['clavicle_' + s] = (J['clav_in', s], J['shoulder', s])
        seg['upperarm_' + s] = (J['shoulder', s], J['elbow', s])
        seg['forearm_' + s] = (J['elbow', s], J['wrist', s])
        seg['hand_' + s] = (J['wrist', s], J['tip', s])     # hand and fingers move as one piece
        seg['thigh_' + s] = (J['hip', s], J['knee', s])
        seg['shin_' + s] = (J['knee', s], J['ankle', s])
        seg['foot_' + s] = (J['ankle', s], J['ball', s])
        seg['toe_' + s] = (J['ball', s], J['toe', s])
    return seg


def adopt_scan_proportions(J):
    """Rewrite the v1 skeleton (module constants of build_skin_stealer) with the scan's joints: spine, shoulders,
    legs and arm lengths (the concept's arms are about 20 % longer than v1's). The clips are re-solved from these
    joints, so they follow. Kept from v1: the head (the stolen-face mask, eyes, mouth and JS_CAM hang off it) and
    the arms' hanging directions (the scan stands in an A-pose)."""
    v1_hand = (ss.FJ['L']['middle'][-1] - ss.WRIST['L']).length
    k_hand = 0.5 * sum((J['tip', s] - J['wrist', s]).length for s in SIDES) / v1_hand
    for i in range(5):
        ss.SPINE[i] = J['spine'][i].copy()
    for s in SIDES:
        E0, W0 = ss.ELBOW[s], ss.WRIST[s]
        dir_u, dir_f = (E0 - ss.SHOULDER[s]).normalized(), (W0 - E0).normalized()
        lu = (J['elbow', s] - J['shoulder', s]).length
        lf = (J['wrist', s] - J['elbow', s]).length
        ss.CLAV_IN[s] = J['clav_in', s].copy()
        ss.SHOULDER[s] = J['shoulder', s].copy()
        ss.ELBOW[s] = ss.SHOULDER[s] + dir_u * lu
        ss.WRIST[s] = ss.ELBOW[s] + dir_f * lf
        for name in ('hip', 'knee', 'ankle', 'ball', 'toe'):
            getattr(ss, name.upper())[s] = J[name, s].copy()
    ss.PALM_LEN = ss.PALM_LEN * k_hand
    ss.FINGERS = {n: (off * k_hand, tuple(l * k_hand for l in segs), splay, curls, r * k_hand)
                  for n, (off, segs, splay, curls, r) in ss.FINGERS.items()}
    ss.FJ = {s: ss.finger_joints(s) for s in SIDES}
    ss.BONES = ss.bone_table()
    ss.HEEL = {s: V((ss.ANKLE[s].x, ss.ANKLE[s].y + 0.05, 0.0)) for s in SIDES}
    ss.HAND_C = {s: ss.hand_frame(s)[0] + ss.hand_frame(s)[1] * 0.1 for s in SIDES}
    ss.FINGER_BONES = {s: [n for n in ss.BONES if n.endswith('_' + s) and n.split('_')[0] in
                           ('thumb', 'index', 'middle', 'ring')] for s in SIDES}
    for s in SIDES:
        log('skeleton %s: upper arm %.3f m, forearm %.3f m, hand x%.2f, wrist z %.3f (v1 0.852)' % (
            s, (ss.ELBOW[s] - ss.SHOULDER[s]).length, (ss.WRIST[s] - ss.ELBOW[s]).length, k_hand, ss.WRIST[s].z))


def target_segments(J):
    """Where each scan segment goes: torso and head onto v1, the limbs onto the adopted joints."""
    B = ss.BONES
    dst = {n: (B[n][0], B[n][1]) for n in ('pelvis', 'spine_01', 'spine_02', 'spine_03', 'neck', 'head')}
    for s in SIDES:
        for b in ('clavicle', 'upperarm', 'forearm', 'thigh', 'shin', 'foot', 'toe'):
            dst[b + '_' + s] = (B[b + '_' + s][0], B[b + '_' + s][1])
        w, d, _lh, _np = ss.hand_frame(s)
        dst['hand_' + s] = (w, w + d * (J['tip', s] - J['wrist', s]).length)
    return dst


def seg_weights(P, segs, edges=None, falloff=0.55, smooth=2, radii=None, may_use=None):
    """build_skin_stealer.compute_weights for any set of segments: distance to each segment over its radius,
    limited to the nearest bone's family, Laplacian-smoothed, 4 largest kept, normalised. Returns (names, W).
    may_use(names) -> (N, bones) bool: bones a vertex may not use are left out entirely."""
    names = list(segs)
    idx = {n: i for i, n in enumerate(names)}
    N, nb_ = len(P), len(names)
    D = np.zeros((N, nb_))
    for j, n in enumerate(names):
        h, t = (np.array(tuple(x)) for x in segs[n])
        d = t - h
        tt = np.clip(((P - h) @ d) / (d @ d), 0, 1)
        dist = np.linalg.norm(P - (h + tt[:, None] * d), axis=1)
        r0, r1 = (radii or ss.SEG_R)[n]
        D[:, j] = dist / (r0 + (r1 - r0) * tt)
    if may_use is not None:
        D = np.where(may_use(names), D, 1e9)
    nb = np.eye(nb_, dtype=bool)
    for n in names:
        p = ss.BONES[n][2]
        gp = ss.BONES[p][2] if p else None
        for q in (p, gp):
            if q in idx:
                nb[idx[n], idx[q]] = nb[idx[q], idx[n]] = True
    best = np.argmin(D, axis=1)
    allowed = nb[best]
    dd = D - D[np.arange(N), best][:, None]
    W = np.where(allowed, np.clip(1.0 - dd / falloff, 0, 1) ** 2, 0.0)
    if edges is not None:
        for _ in range(smooth):
            acc = np.zeros_like(W)
            cnt = np.zeros(N)
            np.add.at(acc, edges[:, 0], W[edges[:, 1]])
            np.add.at(acc, edges[:, 1], W[edges[:, 0]])
            np.add.at(cnt, edges[:, 0], 1)
            np.add.at(cnt, edges[:, 1], 1)
            W = np.where(allowed & (D < 1e8), 0.5 * W + 0.5 * acc / np.maximum(cnt, 1)[:, None], 0.0)
    order = np.argsort(-W, axis=1)[:, 4:]
    np.put_along_axis(W, order, 0.0, axis=1)
    W /= np.maximum(W.sum(axis=1, keepdims=True), 1e-9)
    return names, W


def segment_map(src, dst):
    """4x4 taking segment src (head, tail) onto dst: move the head, turn the direction, stretch along the bone."""
    hs, ts = src
    hd, td = dst
    ds, dd = ts - hs, td - hd
    R = ds.normalized().rotation_difference(dd.normalized()).to_matrix().to_4x4()
    u = np.array(tuple(ds.normalized()))
    S = np.eye(4)
    S[:3, :3] += (dd.length / ds.length - 1.0) * np.outer(u, u)
    return np.array(Matrix.Translation(hd)) @ np.array(R) @ S @ np.array(Matrix.Translation(-hs))


def mesh_edges(tri):
    e = np.vstack([tri[:, [0, 1]], tri[:, [1, 2]], tri[:, [2, 0]]])
    e.sort(axis=1)
    return np.unique(e, axis=0)


def fit_to_skeleton(co, tri):
    """Returns the scan moved onto the skeleton (fitted), the scan itself after a rigid shift (same vertex order),
    and the measured joints. Also rewrites the skeleton constants in build_skin_stealer (adopt_scan_proportions)."""
    co = co.copy()
    co[:, 1] += ss.SPINE[0].y - scan_joints(co)['spine'][0].y     # pelvis onto the v1 pelvis plane
    J = scan_joints(co)
    adopt_scan_proportions(J)
    src = scan_segments(J)
    dst = target_segments(J)
    for n in FIT_BONES:
        (hs, ts), (hd, td) = src[n], dst[n]
        ang = math.degrees((ts - hs).angle(td - hd))
        log('fit %-12s head moves %4.1f cm, turns %5.1f deg, length x%.2f' % (
            n, (hd - hs).length * 100, ang, (td - hd).length / (ts - hs).length))
    radii = dict(ss.SEG_R)
    for s in SIDES:
        radii['hand_' + s] = (0.045, 0.03)
    edges = mesh_edges(tri)
    names, W = seg_weights(co, src, edges, smooth=6, radii=radii)
    out = np.zeros_like(co)
    for j, n in enumerate(names):
        w = W[:, j]
        m = w > 0
        if not m.any():
            continue
        M = segment_map(src[n], dst[n])
        out[m] += w[m, None] * (co[m] @ M[:3, :3].T + M[:3, 3])
    grow = edge_growth(co, out, tri)
    log('fit: %d triangles grew by more than 1 cm (worst %.1f cm)' % (int((grow > 0.01).sum()), grow.max() * 100))
    part = np.array(names)[np.argmax(W, axis=1)]
    return out, co, J, part


def edge_growth(a, b, tri):
    def longest(P):
        return np.maximum.reduce([np.linalg.norm(P[tri[:, i]] - P[tri[:, j]], axis=1)
                                  for i, j in ((0, 1), (1, 2), (2, 0))])
    return longest(b) - longest(a)


def make_mesh(name, co, tri):
    me = bpy.data.meshes.new(name)
    me.vertices.add(len(co))
    me.vertices.foreach_set('co', co.astype(np.float32).ravel())
    me.loops.add(len(tri) * 3)
    me.loops.foreach_set('vertex_index', tri.astype(np.int32).ravel())
    me.polygons.add(len(tri))
    me.polygons.foreach_set('loop_start', np.arange(0, len(tri) * 3, 3, dtype=np.int32))
    me.update(calc_edges=True)
    me.validate()
    obj = bpy.data.objects.new(name, me)
    bpy.context.scene.collection.objects.link(obj)
    for p in me.polygons:
        p.use_smooth = True
    return obj


def check_fit(obj):
    """Fitted scan with the v1 joints as red dots, front and side."""
    dots = common.material('joint', color=(0.9, 0.05, 0.05), emission=(0.9, 0.05, 0.05), emission_strength=3)
    made = []
    for n, (h, t, _p) in ss.BONES.items():
        if n in FIT_BONES or n.startswith(('index', 'middle', 'ring', 'thumb')):
            bpy.ops.mesh.primitive_uv_sphere_add(radius=0.012, location=h, segments=8, ring_count=6)
            o = bpy.context.active_object
            common.assign(o, dots)
            made.append(o)
    common.assign(obj, common.material('check', color=(0.75, 0.72, 0.6), roughness=0.7))
    tmp = ss.TMP
    for name, cam in (('front', (0.0, -4.2, 1.15)), ('side', (4.2, 0.0, 1.15)), ('back', (0.0, 4.2, 1.15))):
        common.render_preview('scan_fit_%s.png' % name, cam, target=(0, 0, 1.15), lens=35, resolution=(700, 900),
                              directory=tmp)
    log('fit check renders in', tmp)
    for o in made:
        bpy.data.objects.remove(o, do_unlink=True)


