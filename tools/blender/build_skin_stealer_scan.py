def load_scan():
    """Vertices (N, 3) and triangles (M, 3) of the scan in Blender axes: +Z up, facing -Y, its left at +X."""
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=str(SCAN))
    objs = [o for o in bpy.data.objects if o not in before]
    cos, tris, base = [], [], 0
    for o in objs:
        if o.type != 'MESH':
            continue
        me = o.data
        n = len(me.vertices)
        co = np.zeros(n * 3)
        me.vertices.foreach_get('co', co)
        co = co.reshape(-1, 3)
        M = np.array(o.matrix_world)
        co = co @ M[:3, :3].T + M[:3, 3]
        me.calc_loop_triangles()
        t = np.zeros(len(me.loop_triangles) * 3, np.int64)
        me.loop_triangles.foreach_get('vertices', t)
        cos.append(co)
        tris.append(t.reshape(-1, 3) + base)
        base += n
    for o in objs:
        bpy.data.objects.remove(o, do_unlink=True)
    co, tri = np.vstack(cos), np.vstack(tris)
    # height 2.27 m, feet on the floor, centred between the feet, legs on the v1 skeleton's plane
    z0, z1 = co[:, 2].min(), co[:, 2].max()
    co = (co - np.array([0, 0, z0])) * (ss.HEIGHT / (z1 - z0))
    feet = co[co[:, 2] < 0.10]
    co[:, 0] -= 0.5 * (feet[feet[:, 0] > 0, 0].mean() + feet[feet[:, 0] < 0, 0].mean())
    legs = co[(co[:, 2] > 0.3) & (co[:, 2] < 0.9) & (np.abs(co[:, 0]) < 0.25)]
    co[:, 1] -= legs[:, 1].mean() - 0.0
    log('scan', len(co), 'verts', len(tri), 'tris', 'bbox', co.min(0).round(3), co.max(0).round(3))
    return co, tri


